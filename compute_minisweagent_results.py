#!/usr/bin/env python3
"""
Compute classification metrics only for the manually evaluated sample.

The script reads:

1. predictions_agg.csv generated by the agentic experiment
2. the corresponding sample CSV (e.g. data/sample/IM.csv)

It matches sample targets against experiment units, normalizing FQNs:

    sample:
        org.apache.commons.io.CloseableURLConnection

    predictions:
        org_apache_commons_io_CloseableURLConnection

Metrics are computed ONLY for elements present in the sample.

Metrics:
    - Accuracy
    - Precision
    - Recall
    - F1
    - Matthews Correlation Coefficient (MCC)
    - Cohen's Kappa
    - Confusion matrix

Example:

    python compute_minisweagent_results.py \
        --smell insufficient_modularization \
        --model moonshotai_kimi-k3 \
        --output metrics.csv
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    cohen_kappa_score,
    confusion_matrix,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
)


BASE_DIR = Path("/data/henrique/detecting_smells_study")

REPO_DIR = (
    BASE_DIR
    / "Architecture-Smell-Detection-using-Agents"
)

SAMPLE_DIR = BASE_DIR / "data" / "sample"


# Maps the smell argument to its manually evaluated sample file.
SAMPLE_FILES = {
    "insufficient_modularization": "IM.csv",
    "god_component": "GC.csv",
    "hublike_modularization": "HM.csv",
    "unstable_dependency": "UD.csv",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Compute metrics for the manually evaluated sample only."
        )
    )

    parser.add_argument(
        "--smell",
        required=True,
        choices=sorted(SAMPLE_FILES),
        help="Architecture smell.",
    )

    parser.add_argument(
        "--model",
        required=True,
        help=(
            "Model directory under results/agentic, "
            "e.g. moonshotai_kimi-k3."
        ),
    )

    parser.add_argument(
        "--repo",
        type=Path,
        default=REPO_DIR,
        help=(
            "Path to Architecture-Smell-Detection-using-Agents. "
            f"Default: {REPO_DIR}"
        ),
    )

    parser.add_argument(
        "--sample-dir",
        type=Path,
        default=SAMPLE_DIR,
        help=(
            "Directory containing GC.csv, HM.csv, IM.csv and UD.csv. "
            f"Default: {SAMPLE_DIR}"
        ),
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=None,
        help=(
            "Optional direct path to predictions_agg.csv. "
            "Overrides the automatically constructed path."
        ),
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Optional CSV file where metrics will be written.",
    )

    return parser.parse_args()


def normalize_identifier(value: object) -> str:
    """
    Normalize a Java FQN/unit identifier so sample and prediction identifiers
    can be compared.

    Examples:

        org.apache.commons.io.CloseableURLConnection
            ->
        org_apache_commons_io_CloseableURLConnection

        org_apache_commons_io_CloseableURLConnection
            ->
        org_apache_commons_io_CloseableURLConnection
    """

    if pd.isna(value):
        return ""

    value = str(value).strip()

    # Main difference observed between the two datasets:
    # sample uses "." while predictions use "_".
    value = value.replace(".", "_")

    # Make repeated underscores harmless.
    value = re.sub(r"_+", "_", value)

    return value


def normalize_project(value: object) -> str:
    """
    Normalize repository/project names for matching.
    """

    if pd.isna(value):
        return ""

    value = str(value).strip().lower()

    # Be tolerant to superficial project naming differences.
    value = value.replace("_", "-")

    return value


def get_predictions_path(args: argparse.Namespace) -> Path:
    if args.input is not None:
        return args.input

    return (
        args.repo
        / "results"
        / "agentic"
        / args.smell
        / args.model
        / "predictions_agg.csv"
    )


def get_sample_path(args: argparse.Namespace) -> Path:
    sample_filename = SAMPLE_FILES[args.smell]
    return args.sample_dir / sample_filename


def load_predictions(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"predictions_agg.csv not found: {path}"
        )

    df = pd.read_csv(path)

    required = {
        "project",
        "designite",
        "detection_majority",
    }

    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            "predictions_agg.csv is missing required columns: "
            + ", ".join(sorted(missing))
        )

    # score.py currently contains both unit and unit_id.
    # Prefer unit_id because it is intended to be a stable identifier.
    if "unit_id" in df.columns:
        identifier_column = "unit_id"
    elif "unit" in df.columns:
        identifier_column = "unit"
    else:
        raise ValueError(
            "predictions_agg.csv must contain either "
            "'unit_id' or 'unit'."
        )

    print(
        f"Using predictions identifier column: {identifier_column}"
    )

    df["_prediction_identifier"] = df[identifier_column].map(
        normalize_identifier
    )

    df["_prediction_project"] = df["project"].map(
        normalize_project
    )

    return df


def load_sample(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"sample file not found: {path}"
        )

    df = pd.read_csv(path)

    required = {
        "repository",
        "target",
        "human_label",
    }

    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            "sample CSV is missing required columns: "
            + ", ".join(sorted(missing))
        )

    df["_sample_identifier"] = df["target"].map(
        normalize_identifier
    )

    df["_sample_project"] = df["repository"].map(
        normalize_project
    )

    return df


def match_sample(
    predictions: pd.DataFrame,
    sample: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Keep only predictions corresponding to targets in the manual sample.

    Matching uses both:

        repository/project
        target/unit_id

    This avoids accidental matches when two projects contain similarly named
    classes.
    """

    merged = sample.merge(
        predictions,
        left_on=[
            "_sample_project",
            "_sample_identifier",
        ],
        right_on=[
            "_prediction_project",
            "_prediction_identifier",
        ],
        how="left",
        indicator=True,
        suffixes=("_sample", "_prediction"),
    )

    matched = merged.loc[
        merged["_merge"] == "both"
    ].copy()

    unmatched = merged.loc[
        merged["_merge"] == "left_only"
    ].copy()

    return matched, unmatched


def compute_metrics(df: pd.DataFrame) -> dict:
    n_sample_matched = len(df)

    # We now use the manually assigned label from the sample as ground truth.
    valid_mask = (
        df["human_label"].notna()
        & df["detection_majority"].notna()
    )

    evaluated = df.loc[valid_mask].copy()

    n_evaluated = len(evaluated)
    n_excluded_prediction = n_sample_matched - n_evaluated

    if n_evaluated == 0:
        raise ValueError(
            "No evaluable sample rows found after matching."
        )

    y_true = evaluated["human_label"].astype(int)
    y_pred = evaluated["detection_majority"].astype(int)

    invalid_truth = ~y_true.isin([0, 1])

    if invalid_truth.any():
        values = sorted(
            y_true[invalid_truth].unique().tolist()
        )

        raise ValueError(
            f"human_label contains values other than 0/1: {values}"
        )

    invalid_prediction = ~y_pred.isin([0, 1])

    if invalid_prediction.any():
        values = sorted(
            y_pred[invalid_prediction].unique().tolist()
        )

        raise ValueError(
            "detection_majority contains values other than 0/1: "
            f"{values}"
        )

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        y_pred,
        labels=[0, 1],
    ).ravel()

    return {
        "n_sample_matched": n_sample_matched,
        "n_evaluated": n_evaluated,
        "n_excluded_prediction": n_excluded_prediction,

        "n_positive_ground_truth": int(
            (y_true == 1).sum()
        ),

        "n_negative_ground_truth": int(
            (y_true == 0).sum()
        ),

        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),

        "accuracy": accuracy_score(
            y_true,
            y_pred,
        ),

        "precision": precision_score(
            y_true,
            y_pred,
            pos_label=1,
            zero_division=0,
        ),

        "recall": recall_score(
            y_true,
            y_pred,
            pos_label=1,
            zero_division=0,
        ),

        "f1": f1_score(
            y_true,
            y_pred,
            pos_label=1,
            zero_division=0,
        ),

        "mcc": matthews_corrcoef(
            y_true,
            y_pred,
        ),

        "cohen_kappa": cohen_kappa_score(
            y_true,
            y_pred,
        ),
    }


def print_unmatched(
    unmatched: pd.DataFrame,
) -> None:
    if unmatched.empty:
        print("All sample targets were found in predictions_agg.csv.")
        return

    print()
    print("WARNING: sample targets not found in predictions:")
    print("-" * 80)

    columns = [
        "repository",
        "target",
    ]

    print(
        unmatched[columns]
        .to_string(index=False)
    )

    print()


def print_metrics(
    smell: str,
    model: str,
    predictions_path: Path,
    sample_path: Path,
    n_sample: int,
    n_unmatched: int,
    metrics: dict,
) -> None:
    print()
    print("=" * 72)
    print("SAMPLE CLASSIFICATION METRICS")
    print("=" * 72)

    print(f"Smell       : {smell}")
    print(f"Model       : {model}")
    print(f"Predictions : {predictions_path}")
    print(f"Sample      : {sample_path}")

    print()
    print("Sample matching")
    print("-" * 72)

    print(f"Sample rows             : {n_sample}")
    print(
        f"Matched predictions     : "
        f"{metrics['n_sample_matched']}"
    )
    print(f"Unmatched sample rows   : {n_unmatched}")
    print(
        f"Evaluated predictions   : "
        f"{metrics['n_evaluated']}"
    )
    print(
        f"Missing/tied prediction : "
        f"{metrics['n_excluded_prediction']}"
    )

    print()
    print("Ground truth")
    print("-" * 72)

    print(
        f"Positive                : "
        f"{metrics['n_positive_ground_truth']}"
    )

    print(
        f"Negative                : "
        f"{metrics['n_negative_ground_truth']}"
    )

    print()
    print("Confusion matrix")
    print("-" * 72)

    print(
        f"TN: {metrics['tn']:6d}    "
        f"FP: {metrics['fp']:6d}"
    )

    print(
        f"FN: {metrics['fn']:6d}    "
        f"TP: {metrics['tp']:6d}"
    )

    print()
    print("Metrics")
    print("-" * 72)

    print(
        f"Accuracy                 : "
        f"{metrics['accuracy']:.6f}"
    )

    print(
        f"Precision                : "
        f"{metrics['precision']:.6f}"
    )

    print(
        f"Recall                   : "
        f"{metrics['recall']:.6f}"
    )

    print(
        f"F1                       : "
        f"{metrics['f1']:.6f}"
    )

    print(
        f"MCC                      : "
        f"{metrics['mcc']:.6f}"
    )

    print(
        f"Cohen's Kappa            : "
        f"{metrics['cohen_kappa']:.6f}"
    )

    print("=" * 72)
    print()


def save_metrics(
    path: Path,
    smell: str,
    model: str,
    predictions_path: Path,
    sample_path: Path,
    n_sample: int,
    n_unmatched: int,
    metrics: dict,
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    row = {
        "smell": smell,
        "model": model,
        "predictions_file": str(predictions_path),
        "sample_file": str(sample_path),
        "n_sample": n_sample,
        "n_unmatched": n_unmatched,
        **metrics,
    }

    pd.DataFrame([row]).to_csv(
        path,
        index=False,
    )

    print(f"Metrics written to: {path}")


def main() -> None:
    args = parse_args()

    predictions_path = get_predictions_path(args)
    sample_path = get_sample_path(args)

    try:
        predictions = load_predictions(
            predictions_path
        )

        sample = load_sample(
            sample_path
        )

        matched, unmatched = match_sample(
            predictions,
            sample,
        )

        print()
        print(f"Sample rows loaded      : {len(sample)}")
        print(f"Sample rows matched     : {len(matched)}")
        print(f"Sample rows unmatched   : {len(unmatched)}")

        print_unmatched(unmatched)

        metrics = compute_metrics(
            matched
        )

    except (
        FileNotFoundError,
        ValueError,
    ) as exc:
        print(
            f"ERROR: {exc}",
            file=sys.stderr,
        )
        sys.exit(1)

    print_metrics(
        smell=args.smell,
        model=args.model,
        predictions_path=predictions_path,
        sample_path=sample_path,
        n_sample=len(sample),
        n_unmatched=len(unmatched),
        metrics=metrics,
    )

    if args.output is not None:
        save_metrics(
            path=args.output,
            smell=args.smell,
            model=args.model,
            predictions_path=predictions_path,
            sample_path=sample_path,
            n_sample=len(sample),
            n_unmatched=len(unmatched),
            metrics=metrics,
        )


if __name__ == "__main__":
    main()